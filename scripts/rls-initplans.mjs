import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const identifier = (value) => '"' + value.replaceAll('"', '""') + '"';

export function validateSnapshot(policies) {
  if (!Array.isArray(policies) || policies.length === 0)
    throw Error("Empty policy snapshot");
  const seen = new Set();
  for (const policy of policies) {
    const key = JSON.stringify([
      policy.schemaname,
      policy.tablename,
      policy.policyname,
    ]);
    if (seen.has(key)) throw Error("Duplicate policy identity");
    seen.add(key);
    if (policy.schemaname !== "public")
      throw Error("Only the public schema is in scope");
    for (const field of [
      "tablename",
      "policyname",
      "roles",
      "cmd",
      "permissive",
    ]) {
      if (typeof policy[field] !== "string" || !policy[field])
        throw Error(`Missing ${field}`);
    }
    if (!["SELECT", "INSERT", "UPDATE", "DELETE", "ALL"].includes(policy.cmd))
      throw Error("Invalid command");
    if (!["PERMISSIVE", "RESTRICTIVE"].includes(policy.permissive))
      throw Error("Invalid policy mode");
    for (const field of ["qual", "with_check"]) {
      if (policy[field] !== null && typeof policy[field] !== "string")
        throw Error(`Invalid ${field}`);
      // The input is a reviewed pg_policies export, never a client-supplied predicate.
      if (policy[field]?.includes("$policy_snapshot$"))
        throw Error("Snapshot delimiter collision");
    }
    if (
      !/auth\.(uid|role)\(\)/.test(
        `${policy.qual ?? ""} ${policy.with_check ?? ""}`,
      )
    ) {
      throw Error("No request identity call");
    }
    if (
      /\bSELECT\s+auth\.(uid|role)\(\)/i.test(
        `${policy.qual ?? ""} ${policy.with_check ?? ""}`,
      )
    ) {
      throw Error("Already wrapped identity call: refresh the snapshot");
    }
  }
  return policies;
}

export function compile(policies, { rollback = false } = {}) {
  validateSnapshot(policies);
  const snapshot = JSON.stringify(policies);
  return `-- Generated by scripts/rls-initplans.mjs from the reviewed policy snapshot.
-- ${rollback ? "Restore the original predicates" : "Cache row-independent request identity once per statement"}; preserve roles, commands and policy mode.
-- A single DO statement is atomic. Abort on drift or lock contention; never retry blindly.
-- Run inside a transaction (as Supabase migrations do); rollback has the same requirement.
-- Arm the statement timer before PostgreSQL starts the DO statement.
SET LOCAL statement_timeout = '15s';
SET LOCAL lock_timeout = '2s';
DO $migration$
DECLARE
  expected record;
  actual record;
  expression text;
  new_using text;
  new_check text;
  statement text;
  snapshot constant jsonb := $policy_snapshot$${snapshot}$policy_snapshot$::jsonb;
BEGIN
  -- Lock in a stable order before comparing the catalog, preventing a concurrent
  -- policy edit between the precondition and ALTER POLICY.
  FOR expected IN SELECT DISTINCT p.schemaname, p.tablename
    FROM jsonb_to_recordset(snapshot) AS p(schemaname text, tablename text)
    ORDER BY p.schemaname, p.tablename
  LOOP
    EXECUTE format('LOCK TABLE %I.%I IN SHARE ROW EXCLUSIVE MODE', expected.schemaname, expected.tablename);
  END LOOP;

  FOR expected IN SELECT * FROM jsonb_to_recordset(snapshot) AS p(
    schemaname text, tablename text, policyname text, permissive text,
    roles text, cmd text, qual text, with_check text)
  LOOP
    SELECT * INTO actual FROM pg_policies
      WHERE schemaname = expected.schemaname AND tablename = expected.tablename
        AND policyname = expected.policyname;
    IF NOT FOUND THEN RAISE EXCEPTION 'Missing policy %.%: %', expected.schemaname, expected.tablename, expected.policyname; END IF;
    IF actual.roles::text IS DISTINCT FROM expected.roles
      OR actual.cmd IS DISTINCT FROM expected.cmd
      OR actual.permissive IS DISTINCT FROM expected.permissive
    THEN RAISE EXCEPTION 'Policy grants drifted: %.%: %', expected.schemaname, expected.tablename, expected.policyname; END IF;

    -- pg_get_expr deparses scalar subqueries with an AS uid/role alias.
    -- Remove only that exact wrapper for the equivalence guard.
    expression := regexp_replace(actual.qual, '\\(\\s*SELECT auth\\.(uid|role)\\(\\) AS (uid|role)\\s*\\)', 'auth.\\1()', 'g');
    IF expression IS DISTINCT FROM expected.qual THEN
      RAISE EXCEPTION 'USING drifted: %.%: %', expected.schemaname, expected.tablename, expected.policyname;
    END IF;
    expression := regexp_replace(actual.with_check, '\\(\\s*SELECT auth\\.(uid|role)\\(\\) AS (uid|role)\\s*\\)', 'auth.\\1()', 'g');
    IF expression IS DISTINCT FROM expected.with_check THEN
      RAISE EXCEPTION 'WITH CHECK drifted: %.%: %', expected.schemaname, expected.tablename, expected.policyname;
    END IF;

    new_using := ${rollback ? "expected.qual" : "regexp_replace(expected.qual, 'auth\\.(uid|role)\\(\\)', '(SELECT auth.\\1())', 'g')"};
    new_check := ${rollback ? "expected.with_check" : "regexp_replace(expected.with_check, 'auth\\.(uid|role)\\(\\)', '(SELECT auth.\\1())', 'g')"};
    statement := format('ALTER POLICY %I ON %I.%I', expected.policyname, expected.schemaname, expected.tablename);
    IF new_using IS NOT NULL THEN statement := statement || ' USING (' || new_using || ')'; END IF;
    IF new_check IS NOT NULL THEN statement := statement || ' WITH CHECK (' || new_check || ')'; END IF;
    EXECUTE statement;
  END LOOP;
END
$migration$;
`;
}

export function fixture(policies) {
  validateSnapshot(policies);
  const tables = [
    ...new Set([...policies.map((p) => p.tablename), "book_authors"]),
  ].sort();
  const columns = [
    "id",
    "user_id",
    "creator_id",
    "owner_id",
    "book_id",
    "world_id",
    "deployer_id",
    "platform_id",
    "affiliate_id",
    "deployment_id",
    "doc_id",
    "forked_by",
  ];
  return (
    tables
      .map(
        (table) =>
          `CREATE TABLE public.${identifier(table)} (${columns.map((c) => `${identifier(c)} uuid`).join(", ")}, status text, visibility text, role text);\nALTER TABLE public.${identifier(table)} ENABLE ROW LEVEL SECURITY;`,
      )
      .join("\n") +
    "\n" +
    policies
      .map((p) => {
        const roles = p.roles
          .slice(1, -1)
          .split(",")
          .map(identifier)
          .join(", ");
        return `CREATE POLICY ${identifier(p.policyname)} ON public.${identifier(p.tablename)} AS ${p.permissive} FOR ${p.cmd} TO ${roles}${p.qual ? ` USING (${p.qual})` : ""}${p.with_check ? ` WITH CHECK (${p.with_check})` : ""};`;
      })
      .join("\n") +
    "\n"
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const policies = JSON.parse(
    readFileSync(
      new URL("./sql/arcanea-auth-policy-snapshot.json", import.meta.url),
      "utf8",
    ),
  );
  process.stdout.write(
    process.argv.includes("--fixture")
      ? fixture(policies)
      : compile(policies, { rollback: process.argv.includes("--rollback") }),
  );
}
