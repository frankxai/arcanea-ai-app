import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const commandDir = path.join(root, ".claude", "commands");
const skillsDir = path.join(root, ".claude", "skills");
const codexDir = path.join(root, ".codex");
const agentsDir = path.join(root, ".agents");
const checkOnly = process.argv.includes("--check");

function posixRelative(filePath) {
  return path.relative(root, filePath).split(path.sep).join("/");
}

function readText(filePath) {
  return fs.readFileSync(filePath, "utf8");
}

function listFiles(dir) {
  if (!fs.existsSync(dir)) {
    return [];
  }

  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "worktrees" || entry.name === ".claude-flow") {
        continue;
      }
      results.push(...listFiles(fullPath));
      continue;
    }
    if (entry.isFile()) {
      results.push(fullPath);
    }
  }
  return results;
}

function parseFrontmatter(text) {
  const normalized = text.replace(/^\uFEFF/, "");
  const match = normalized.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
  if (!match) {
    return {};
  }

  const raw = match[1].trim();
  const data = {};
  for (const line of raw.split(/\r?\n/)) {
    const match = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!match) {
      continue;
    }
    const key = match[1].trim();
    const value = match[2].trim().replace(/^["']|["']$/g, "");
    data[key] = value;
  }
  return data;
}

function firstHeading(text) {
  const match = text.match(/^#\s+(.+)$/m);
  return match?.[1]?.trim() ?? "";
}

function firstNonEmptyLine(text) {
  const normalized = text.replace(/^\uFEFF/, "");
  const withoutFrontmatter = normalized.startsWith("---")
    ? normalized.replace(/^---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/, "")
    : normalized;
  return (
    withoutFrontmatter
      .split(/\r?\n/)
      .map((line) => line.trim())
      .find((line) => line && !line.startsWith("#")) ?? ""
  );
}

function summarize(filePath) {
  const text = readText(filePath);
  const fm = parseFrontmatter(text);
  return {
    title: fm.name || firstHeading(text) || path.basename(filePath, ".md"),
    description: fm.description || firstNonEmptyLine(text),
  };
}

function commandEntries() {
  return listFiles(commandDir)
    .filter((file) => path.extname(file).toLowerCase() === ".md")
    .filter((file) => path.dirname(file) === commandDir)
    .map((file) => {
      const slug = path.basename(file, ".md");
      const meta = summarize(file);
      return {
        command: `/${slug}`,
        file: posixRelative(file),
        description: meta.description,
      };
    })
    .sort((a, b) => a.command.localeCompare(b.command));
}

function isRootSkillMarkdown(file) {
  return path.dirname(file) === skillsDir && path.extname(file).toLowerCase() === ".md";
}

function isSkillEntrypoint(file) {
  const base = path.basename(file).toLowerCase();
  return base === "skill.md" || isRootSkillMarkdown(file);
}

function skillNameFromPath(file) {
  if (isRootSkillMarkdown(file)) {
    return path.basename(file, ".md");
  }

  const dir = path.basename(path.dirname(file));
  const parent = path.basename(path.dirname(path.dirname(file)));
  if (["arcanea", "creative", "development", "industry", "community", "premium", "meta", "oss", "external", "academy"].includes(parent)) {
    return `${parent}/${dir}`;
  }
  return dir;
}

function skillEntries() {
  return listFiles(skillsDir)
    .filter(isSkillEntrypoint)
    .filter((file) => !["SKILL_ARCHITECTURE.md", "SKILL_COMBINATIONS.md", "SKILL_TEMPLATES.md", "HARVESTED_SKILLS.md"].includes(path.basename(file)))
    .map((file) => {
      const meta = summarize(file);
      return {
        skill: skillNameFromPath(file),
        title: meta.title,
        file: posixRelative(file),
        description: meta.description,
      };
    })
    .sort((a, b) => a.skill.localeCompare(b.skill));
}

function markdownTable(headers, rows) {
  const toAscii = (value) =>
    String(value ?? "")
      .normalize("NFKD")
      .replace(/[\u2018\u2019]/g, "'")
      .replace(/[\u201C\u201D]/g, '"')
      .replace(/[\u2013\u2014]/g, "-")
      .replace(/[\u2192\u27A1]/g, "->")
      .replace(/[^\x09\x0A\x0D\x20-\x7E]/g, "");
  const escapeCell = (value) => toAscii(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(escapeCell).join(" | ")} |`),
  ].join("\n");
}

function commandIndexBody(entries) {
  return `# Claude Command Index

Generated by \`node scripts/generate-codex-claude-bridge.mjs\`.

Codex uses this file to resolve slash commands to Claude command specs.

${markdownTable(["Command", "File", "Description"], entries.map((entry) => [entry.command, entry.file, entry.description]))}
`;
}

function skillIndexBody(entries) {
  return `# Claude Skill Index

Generated by \`node scripts/generate-codex-claude-bridge.mjs\`.

Codex uses this file to resolve Claude skill names to their source entrypoints.

${markdownTable(["Skill", "Title", "File", "Description"], entries.map((entry) => [entry.skill, entry.title, entry.file, entry.description]))}
`;
}

function checkFile(filePath, body) {
  if (!fs.existsSync(filePath)) {
    return [`missing ${posixRelative(filePath)}`];
  }
  const current = fs.readFileSync(filePath, "utf8");
  if (current !== body) {
    return [`stale ${posixRelative(filePath)}`];
  }
  return [];
}

function writeIndexCopies(fileName, body) {
  if (checkOnly) {
    return checkFile(path.join(agentsDir, fileName), body);
  }

  for (const dir of [codexDir, agentsDir]) {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, fileName), body, "utf8");
  }
  return [];
}

function writeCommandIndex(entries) {
  return writeIndexCopies("claude-command-index.md", commandIndexBody(entries));
}

function writeSkillIndex(entries) {
  return writeIndexCopies("claude-skill-index.md", skillIndexBody(entries));
}

const commands = commandEntries();
const skills = skillEntries();

const failures = [
  ...writeCommandIndex(commands),
  ...writeSkillIndex(skills),
];

if (checkOnly && failures.length > 0) {
  console.error("Claude bridge indexes are out of sync:");
  for (const failure of failures) {
    console.error(`- ${failure}`);
  }
  console.error("Run: node scripts/generate-codex-claude-bridge.mjs");
  process.exit(1);
}

console.log(`${checkOnly ? "Checked" : "Indexed"} ${commands.length} Claude commands.`);
console.log(`${checkOnly ? "Checked" : "Indexed"} ${skills.length} Claude skill entrypoints.`);
