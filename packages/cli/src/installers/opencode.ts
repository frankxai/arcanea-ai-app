import {
  closeSync,
  existsSync,
  fstatSync,
  fsyncSync,
  linkSync,
  lstatSync,
  mkdirSync,
  openSync,
  readFileSync,
  realpathSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { randomUUID } from "node:crypto";
import type {
  InstallPreview,
  InstallResult,
  OverlayLevel,
} from "@arcanea/core";

const PLUGIN_PATH = ".opencode/plugins/arcanea-creator.ts";

/** Project adapter only. OpenCode remains responsible for models and permissions. */
export class OpenCodeProjectInstaller {
  private readonly mcpEntry: string;

  constructor(mcpEntry: string) {
    this.mcpEntry = mcpEntry;
  }

  private plan(projectDir: string, level: OverlayLevel, checkEntry = true) {
    if (!["minimal", "standard"].includes(level)) {
      throw new Error(
        "OpenCode supports minimal (core tools) or standard (core and world tools).",
      );
    }
    const requested = resolve(projectDir);
    const rootStat = lstatSync(requested);
    if (!rootStat.isDirectory() || rootStat.isSymbolicLink()) {
      throw new Error(
        "Choose an existing project directory without a symlink or junction.",
      );
    }
    const root = realpathSync(requested);
    if (!this.mcpEntry)
      throw new Error(
        "OpenCode requires --mcp-entry pointing to an installed Arcanea MCP cli.js.",
      );
    const entry = resolve(this.mcpEntry);
    if (checkEntry && !lstatSync(entry).isFile())
      throw new Error(
        "The MCP entry must be a regular installed JavaScript file.",
      );
    const tools = level === "minimal" ? "core" : "core,world";
    const command = [process.execPath, entry, "--toolsets", tools];
    const content = `// Arcanea project adapter. Generated by @arcanea/cli; preserve local edits.
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export default async function ArcaneaCreator() {
  return {
    config: async (config) => {
      if (config.mcp && Object.prototype.hasOwnProperty.call(config.mcp, 'arcanea')) return;
      config.mcp ??= {};
      config.mcp.arcanea = {
        type: 'local',
        command: ${JSON.stringify(command)},
        enabled: true,
        environment: {
          ARCANEA_DATA_DIR: resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '.arcanea', 'data'),
        },
      };
    },
  };
}
`;
    const target = join(root, PLUGIN_PATH);
    this.inspect(root, target, content);
    return { root, target, content };
  }

  private inspect(root: string, target: string, expected: string): boolean {
    for (const path of [join(root, ".opencode"), dirname(target)]) {
      try {
        const stat = lstatSync(path);
        const physical = realpathSync(path);
        const samePath =
          process.platform === "win32"
            ? physical.toLowerCase() === path.toLowerCase()
            : physical === path;
        if (!stat.isDirectory() || stat.isSymbolicLink() || !samePath) {
          throw new Error(
            "The OpenCode plugin directory must stay inside the selected project without symlinks or junctions.",
          );
        }
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      }
    }
    try {
      const fd = openSync(target, "r");
      try {
        const opened = fstatSync(fd, { bigint: true });
        const matchesOpenedFile = () => {
          const named = lstatSync(target, { bigint: true });
          return (
            named.isFile() &&
            !named.isSymbolicLink() &&
            named.dev === opened.dev &&
            named.ino === opened.ino
          );
        };
        if (
          !opened.isFile() ||
          !matchesOpenedFile() ||
          readFileSync(fd, "utf8") !== expected ||
          !matchesOpenedFile()
        ) {
          throw new Error(
            `Preserving an existing or modified ${PLUGIN_PATH}; review it before changing installation options.`,
          );
        }
        return true;
      } finally {
        closeSync(fd);
      }
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      return false;
    }
  }

  async preview(
    projectDir: string,
    level: OverlayLevel,
  ): Promise<InstallPreview> {
    const { root, target, content } = this.plan(projectDir, level);
    return {
      filesToCreate: this.inspect(root, target, content)
        ? []
        : [
            {
              path: target,
              description:
                "Project-local Arcanea MCP adapter; keeps existing OpenCode settings",
            },
          ],
      filesToModify: [],
      estimatedSize: `${Buffer.byteLength(content)} bytes`,
    };
  }

  async install(
    projectDir: string,
    level: OverlayLevel,
  ): Promise<InstallResult> {
    const { root, target, content } = this.plan(projectDir, level);
    if (this.inspect(root, target, content)) return this.result([]);
    for (const directory of [join(root, ".opencode"), dirname(target)]) {
      try {
        mkdirSync(directory);
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
      }
      this.inspect(root, target, content);
    }
    const temporary = join(
      dirname(target),
      `.arcanea-creator-${randomUUID()}.tmp`,
    );
    let created = false;
    let linked = false;
    try {
      const fd = openSync(temporary, "wx", 0o600);
      created = true;
      try {
        writeFileSync(fd, content, "utf8");
        fsyncSync(fd);
      } finally {
        closeSync(fd);
      }
      this.inspect(root, target, content);
      // A hard link makes a complete file visible atomically and refuses replacement.
      try {
        linkSync(temporary, target);
        linked = true;
      } catch (error) {
        if (
          (error as NodeJS.ErrnoException).code !== "EEXIST" ||
          !this.inspect(root, target, content)
        )
          throw error;
      }
      this.inspect(root, target, content);
    } finally {
      if (created && existsSync(temporary)) unlinkSync(temporary);
    }
    return this.result(linked ? [target] : []);
  }

  async remove(
    projectDir: string,
    level: OverlayLevel,
  ): Promise<InstallResult> {
    const { root, target, content } = this.plan(projectDir, level, false);
    if (this.inspect(root, target, content)) unlinkSync(target);
    return {
      success: true,
      filesCreated: [],
      filesModified: [],
      warnings: [],
      nextSteps: [
        "The matching Arcanea plugin is removed. Restart OpenCode; saved worlds and all other settings remain available.",
      ],
    };
  }

  private result(filesCreated: string[]): InstallResult {
    return {
      success: true,
      filesCreated,
      filesModified: [],
      warnings: [],
      nextSteps: [
        "Restart OpenCode in this project, then run opencode mcp list to check the Arcanea connection.",
        "Choose your model and permissions in OpenCode. The adapter adds tools without changing them.",
        "An existing mcp.arcanea entry takes precedence, including enabled: false.",
        "Saved worlds use .arcanea/data in this project unless an existing Arcanea server specifies its own storage.",
      ],
    };
  }
}
